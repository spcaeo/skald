MANUAL = 'curl -sI https://{}/ | grep -iE "server|x-powered-by"'
SUMMARY = ("Your site's firewall stopped our check, so we can't see what it shows. That's often good "
           "news: it blocks automated scanners too.")


def home(page, host="www.example.com"):
    return run(host, Net(names={host: [PUBLIC]}, pages={f"https://{host}/": page}))


class Blocked(unittest.TestCase):
    def assert_blocked(self, got, host, firewalls, marks):
        evidenced(self, got)
        self.assertFalse(got["reached"])
        self.assertEqual(got["reason"], "blocked")
        self.assertEqual(got["summary"], SUMMARY)
        self.assertEqual(got["block"]["next"], "To see the details, run the same check from your own computer:")
        self.assertEqual(got["counts"], {"act": 0, "check": 0, "tips": 0, "good": 0})
        self.assertEqual(got["products"], [], "nothing read from a page we could not check")
        [card] = got["cards"]
        self.assertEqual((card["kind"], card["title"]), ("unknown", f"{host}'s firewall stopped our check"))
        self.assertEqual(card["commands"], [MANUAL.format(host), "php -v"])
        self.assertEqual(got["block"]["commands"], card["commands"])
        self.assertEqual(card["firewalls"], firewalls)
        self.assertIn("It is not a problem with your site", card["means"])
        self.assertIn("Run the same check from your own computer", card["advice"])
        texts = [s["text"] for s in card["saw"]]
        self.assertRegex(texts[0], rf"^We saw https://{re.escape(host)}/ answer {got['block']['status']} ")
        for mark in marks:
            self.assertIn(mark, texts)
        self.assertIn(f"Answered {got['block']['status']}", got["facts"])
        if firewalls:
            self.assertIn(f"Firewall: {' and '.join(firewalls)}", got["facts"])
        return card

    def test_the_three_corpus_shapes(self):
        """A Cloudflare challenge (cf-mitigated), a plain 403 naming no firewall, Sucuri's 503."""
        for name, host, firewalls, marks in (
                ("cloudflare-challenge", "www.example.com", ["Cloudflare"],
                 ["We saw the header Cf-Mitigated: challenge", 'We saw the page title "Just a moment..."']),
                ("blocked-plain-403", "example.com", [], ["We saw the header Server: nginx"]),
                ("blocked-sucuri-503", "www.example.com", ["Sucuri"],
                 ['We saw the page title "Sucuri WebSite Firewall - Access Denied"',
                  "We saw the header X-Sucuri-Id: 11005"])):
            with self.subTest(name):
                _case, got = load(name)
                card = self.assert_blocked(got, host, firewalls, marks)
                if not firewalls:
                    self.assertIn("a firewall or a server rule", card["means"])
                else:
                    self.assertIn(f"{firewalls[0]} answered for your site", card["means"])

    def test_more_firewalls_by_their_own_marks(self):
        for page, firewalls, mark in (
                ((202, {"x-amzn-waf-action": "challenge", "x-amz-cf-id": "EXAMPLE=="}, b"<html></html>"),
                 ["AWS WAF", "CloudFront"], "We saw the header X-Amzn-Waf-Action: challenge"),
                ((403, {"Server": "AkamaiGHost"}, b"<html><title>Access Denied</title></html>"),
                 ["Akamai"], 'We saw the page title "Access Denied"'),
                ((503, {}, b"<html><title>Your access to this site has been limited by the site owner</title>"
                           b"<p>Generated by Wordfence</p></html>"),
                 ["Wordfence"], 'We saw "generated by wordfence" in the page'),
                ((429, {"x-iinfo": "1-2-3", "x-cdn": "Imperva"}, b"too many"),
                 ["Imperva"], "We saw the header X-Iinfo: 1-2-3")):
            with self.subTest(firewalls):
                got = home(page)
                self.assert_blocked(got, "www.example.com", firewalls, [mark])

    def test_a_password_is_not_a_firewall(self):
        got = home((401, {"WWW-Authenticate": 'Basic realm="staging"', "Server": "nginx"}, b"401"))
        evidenced(self, got)
        self.assertEqual(got["reason"], "blocked")
        self.assertEqual(got["block"]["kind"], "password")
        self.assertEqual(got["summary"], "Your site asks for a password, so we can't see what it shows.")
        self.assertEqual(got["block"]["next"], "To see the details, check on the server:")
        [card] = got["cards"]
        self.assertEqual(card["title"], "www.example.com asks for a password, so we could not check it")
        self.assertEqual(card["commands"], ["php -v"])
        self.assertIn('We saw the header Www-Authenticate: Basic realm="staging"', [s["text"] for s in card["saw"]])

    def test_a_503_without_a_firewall_denial_is_a_site_that_is_down(self):
        for page in ((503, {"Server": "nginx"}, b"<html>Service Unavailable</html>"),
                     (503, {"Server": "Sucuri/Cloudproxy", "X-Sucuri-ID": "11005"},
                      b"<html><title>Sucuri WebSite Firewall - Unable to connect to the backend</title></html>")):
            with self.subTest(page[1]):
                got = home(page)
                self.assertEqual((got["reason"], got["error"]), ("error", "the home page answered 503"))
                self.assertEqual(got["cards"][0]["title"], "Could not check www.example.com")
                self.assertIsNone(got["block"])

    def test_the_check_never_disguises_itself(self):
        net = Net(names={"www.example.com": [PUBLIC]}, pages={"https://www.example.com/": (
            403, {"cf-mitigated": "challenge"}, b"Just a moment...")})
        run("www.example.com", net)
        self.assertEqual(len(net.opened), 1, "one request: no retry, no other agent")
        self.assertTrue(net.opened[0]["agent"].startswith("SkaldStackCheck/") or "StackCheck/" in net.opened[0]["agent"])

    def test_blocker_reads_only_blocks(self):
        ok = site_fetch.Answer(200, {"server": ["cloudflare"]}, b"<html>hi</html>", "https://www.example.com/", PUBLIC)
        self.assertIsNone(blocked.blocker(ok, "www.example.com"))


