"""The public check when a firewall answers instead of the site (stack_public_blocked.py), and
the one-line summary of what runs a site (stack_public_cards.stack_words).

A firewall that stops the check is "could not check", never a problem with the site: the
answer says what we saw (the status, the challenge's own mark, the firewall when its own
headers or page name it) and gives the commands to see the details from a network the
firewall lets through. The summaries are a table over the whole corpus
(tests/fixtures/stack_public), each one an English sentence: the platform or the language
first, then the server, then the host, then the CDN.
"""
