# What a summary must never say again: "served by nginx on PHP", "on PHP ... on nginx" twice,
# "behind" with no comma after a clause, an empty part.
WRONG = (r"served by [^,.]* on ", r" on [^,.]* on [^,.]* on ", r"[a-z)0-9] behind ", r",,", r" \.", r"  ")


class Summaries(unittest.TestCase):
    def test_every_case_in_the_corpus_has_its_sentence(self):
        names = sorted(p.name for p in CASES.iterdir() if (p / "case.json").exists())
        self.assertEqual(sorted(SUMMARIES), names, "a new case needs its sentence here")
        for name in names:
            with self.subTest(name):
                _case, got = load(name)
                self.assertEqual(got["summary"], SUMMARIES[name])

    def test_each_sentence_reads_in_order(self):
        for name, text in SUMMARIES.items():
            if text in (None, SUMMARY):
                continue
            with self.subTest(name):
                self.assertRegex(text, r"^(Your site|We can't) ")
                self.assertTrue(text.endswith("."))
                parts = [text.find(w) for w in (" runs ", ", served by ", ", hosted on ", ", behind ")]
                self.assertEqual([p for p in parts if p >= 0], sorted(p for p in parts if p >= 0),
                                 "platform or language, then server, then host, then CDN")
                for w in (" runs ", "served by", "hosted on", "behind"):
                    self.assertLessEqual(text.count(w), 1, w)
                for bad in WRONG:
                    self.assertNotRegex(text, bad)

    def test_every_combination(self):
        def f(product, name, family, version=None, patched=None):
            return {"product": product, "name": name, "family": family, "version": version, "patched": patched}

        def rt(name, version=None, patched=None, under=()):
            return {"product": name.lower(), "name": name, "version": version, "patched": patched,
                    "under": list(under)}
        wp, php = f("wordpress", "WordPress", "cms", "6.7"), rt("PHP", under=["WordPress 6.7"])
        nginx, cf = f("nginx", "nginx", "server"), f("cloudflare", "Cloudflare", "cdn")
        cfront = f("cloudfront", "CloudFront", "cdn")
        netlify = f("netlify", "Netlify", "hosting", patched="Netlify")
        astro = f("astro", "Astro", "js")
        table = [
            ([], [], "We can't see what runs your site"),
            ([cf], [], "We can't see what runs your site; it sits behind Cloudflare"),
            ([nginx], [], "Your site is served by nginx"),
            ([nginx, cf], [], "Your site is served by nginx, behind Cloudflare"),
            ([nginx, cfront], [rt("PHP")], "Your site runs PHP (version hidden) on nginx, behind CloudFront"),
            ([], [rt("PHP", "8.3.10")], "Your site runs PHP 8.3.10"),
            ([wp], [php], "Your site runs WordPress 6.7 on PHP (version hidden)"),
            ([wp, nginx, cf], [php], "Your site runs WordPress 6.7 on PHP (version hidden), served by nginx, "
                                     "behind Cloudflare"),
            ([wp, nginx, cf, cfront], [php], "Your site runs WordPress 6.7 on PHP (version hidden), served by "
                                             "nginx, behind Cloudflare and CloudFront"),
            ([astro, netlify], [], "Your site runs Astro, hosted on Netlify"),
            ([astro, nginx, netlify, cf], [], "Your site runs Astro, served by nginx, hosted on Netlify, behind "
                                              "Cloudflare"),
            ([f("nextjs", "Next.js", "js"), netlify], [rt("Node.js", patched="Netlify", under=["Next.js"])],
             "Your site runs Next.js on Node.js (run by Netlify)"),
            ([netlify], [], "Your site is hosted on Netlify"),
            ([f("shopify", "Shopify", "hosted", patched="Shopify"), nginx, cf],
             [rt("PHP", patched="Shopify")], "Your site runs Shopify, behind Cloudflare"),
            ([astro], [rt("PHP")], "Your site runs Astro"),     # a language not under the platform: not claimed
        ]
        for here, rts, want in table:
            with self.subTest(want):
                self.assertEqual(stack_words(here, rts), want)


