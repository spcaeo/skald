#!/usr/bin/env python3
"""Write docker/nginx.conf, the nginx inside the Docker image, from DEPLOY.md.

DEPLOY.md's sessions-mode blocks (between the skald-nginx-sessions markers)
are the one authoritative nginx config: tests/test_nginx_routes.py checks
that every route the helpers answer reaches the right one. The image uses
the same blocks, so this file is generated, never edited by hand:

    python3 docker/build-nginx-conf.py          # rewrite docker/nginx.conf
    python3 docker/build-nginx-conf.py --check  # exit 1 when it is out of date

What changes for the container, and nothing else:
  * the two snippets are written in place of their `include` lines;
  * hooks get X-Forwarded-Proto from the proxy in front (the container
    itself speaks plain HTTP behind it), else nginx's own $scheme;
  * the listen port and the trusted proxies come from two small files the
    entrypoint writes at start (SKALD_PORT; SKALD_TRUSTED_PROXIES and
    SKALD_REAL_IP_HEADER, the realip lines);
  * `/` goes to `/traffic/`, anything else is 404.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEPLOY = ROOT / "DEPLOY.md"
OUT = ROOT / "docker" / "nginx.conf"
BEGIN, END = "<!-- skald-nginx-sessions:begin -->", "<!-- skald-nginx-sessions:end -->"
RUN = "/tmp/skald-nginx"               # pid, temp files and the two runtime includes
HOOK_PROTO = "proxy_set_header X-Forwarded-Proto $scheme;"


def blocks(text: str) -> tuple[str, str, dict[str, str]]:
    """(http level, server level, {snippet name: body}) from DEPLOY.md."""
    part = text[text.index(BEGIN):text.index(END)]
    http = server = None
    snippets: dict[str, str] = {}
    for block in re.findall(r"```nginx\n(.*?)```", part, re.S):
        head = block.splitlines()[0]
        if head.startswith("# ---- http level"):
            http = block
        elif head.startswith("# ---- server level"):
            server = block
        else:
            name = re.match(r"# ---- /etc/nginx/snippets/(\S+) ----", head)
            if not name:
                raise SystemExit(f"DEPLOY.md: an nginx block with no known heading: {head}")
            snippets[name.group(1)] = "\n".join(block.splitlines()[1:])
    if not http or not server or not snippets:
        raise SystemExit("DEPLOY.md: the sessions-mode http, snippet or server block is missing")
    return http, server, snippets


def inline(server: str, snippets: dict[str, str]) -> str:
    def put(m: re.Match) -> str:
        indent, name = m.group(1), m.group(2)
        if name not in snippets:
            raise SystemExit(f"DEPLOY.md: include of an unknown snippet {name}")
        return "\n".join(indent + line for line in snippets[name].strip().splitlines())
    return re.sub(r"^([ \t]*)include snippets/(\S+);[ \t]*$", put, server, flags=re.M)


def indent(text: str, by: int) -> str:
    pad = " " * by
    return "\n".join(pad + line if line.strip() else "" for line in text.strip().splitlines())


def build(text: str) -> str:
    http, server, snippets = blocks(text)
    server = inline(server, snippets)
    if HOOK_PROTO not in server:
        raise SystemExit("DEPLOY.md: the hooks' X-Forwarded-Proto line moved; update this tool")
    server = server.replace(HOOK_PROTO, "proxy_set_header X-Forwarded-Proto $skald_proto;")
    return f"""\
# GENERATED by docker/build-nginx-conf.py from DEPLOY.md's sessions-mode blocks.
# Do not edit: change DEPLOY.md, then run `python3 docker/build-nginx-conf.py`.
#
# The nginx inside the Docker image. It runs as the image's own user, listens on
# one port (8080 unless SKALD_PORT says otherwise), serves the dashboard files and
# sends every Skald route to the two helpers on 127.0.0.1 in the same container.
# Put HTTPS in front of it (docs/INSTALL.md): the sign-in cookie is Secure.
worker_processes 2;
pid {RUN}/nginx.pid;
error_log stderr warn;

events {{
    worker_connections 512;
}}

http {{
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    sendfile on;
    server_tokens off;
    absolute_redirect off;              # Location: /traffic/, not http://<inside>:8080/traffic/
    access_log off;
    client_body_temp_path {RUN}/body;
    proxy_temp_path {RUN}/proxy;
    fastcgi_temp_path {RUN}/fastcgi;
    uwsgi_temp_path {RUN}/uwsgi;
    scgi_temp_path {RUN}/scgi;

    # The visitor's address from the proxy in front, believed only from
    # SKALD_TRUSTED_PROXIES (nobody by default): the entrypoint writes the
    # set_real_ip_from, real_ip_header and real_ip_recursive lines here.
    include {RUN}/trusted.conf;

{indent(http, 4)}
    # The scheme the visitor used, for signed hooks: the proxy's word, else ours.
    map $http_x_forwarded_proto $skald_proto {{
        default $http_x_forwarded_proto;
        ""      $scheme;
    }}
    # ---- end http level ----

    server {{
        include {RUN}/listen.conf;
        server_name _;

{indent(server, 8)}
        # ---- end server level ----

        location = / {{ return 302 /traffic/; }}
        location / {{ return 404; }}
    }}
}}
"""


def main(argv: list[str]) -> int:
    got = build(DEPLOY.read_text())
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != got:
            print("docker/nginx.conf is out of date: run python3 docker/build-nginx-conf.py",
                  file=sys.stderr)
            return 1
        return 0
    OUT.write_text(got)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
